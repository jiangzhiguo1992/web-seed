// gen_rule_ids 从 check 源码的 rulef("...") 调用生成 rule_ids_gen.go。
//
// 用法（在 scripts/cmd 下）：
//
//	go run ./gen_rule_ids
//	go run ./gen_rule_ids -check
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	dir := flag.String("dir", "internal/check", "check package directory")
	out := flag.String("out", "internal/check/rule_ids_gen.go", "generated file")
	check := flag.Bool("check", false, "fail if generated file is stale")
	flag.Parse()

	ids, err := collect(*dir)
	if err != nil {
		fail(err)
	}
	if len(ids) == 0 {
		fail(fmt.Errorf("no rulef(...) calls found in %s", *dir))
	}
	content, err := render(ids)
	if err != nil {
		fail(err)
	}
	if *check {
		existing, err := os.ReadFile(*out)
		if err != nil {
			fail(err)
		}
		if !bytes.Equal(existing, content) {
			fail(fmt.Errorf("%s is stale; run make gen-rule-ids", *out))
		}
		return
	}
	if err := os.WriteFile(*out, content, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s (%d rule ids)\n", *out, len(ids))
}

func collect(dir string) ([]string, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	fset := token.NewFileSet()
	for _, file := range files {
		name := filepath.Base(file)
		if strings.HasSuffix(name, "_test.go") || name == "rule_ids_gen.go" {
			continue
		}
		f, err := parser.ParseFile(fset, file, nil, 0)
		if err != nil {
			return nil, err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok || sel.Sel.Name != "rulef" || len(call.Args) == 0 {
				return true
			}
			lit, ok := call.Args[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			id, err := strconv.Unquote(lit.Value)
			if err == nil && id != "" {
				seen[id] = true
			}
			return true
		})
	}
	ids := make([]string, 0, len(seen))
	for id := range seen {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	return ids, nil
}

func render(ids []string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./gen_rule_ids; DO NOT EDIT.\n\n")
	buf.WriteString("package check\n\n")
	buf.WriteString("var knownRuleIDs = map[string]bool{\n")
	for _, id := range ids {
		fmt.Fprintf(&buf, "\t%s: true,\n", strconv.Quote(id))
	}
	buf.WriteString("}\n")
	return format.Source(buf.Bytes())
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen-rule-ids:", err)
	os.Exit(1)
}
