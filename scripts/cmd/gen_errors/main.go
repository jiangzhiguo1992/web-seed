// generrors 从 contracts/platform/errors/*.yaml 生成人读错误码视图。
//
// 用法（在 scripts/cmd 下）：
//
//	go run ./gen_errors -root ../..
//	go run ./gen_errors -root ../.. -check
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type errorEntry struct {
	Code      string `yaml:"code"`
	BizCode   int    `yaml:"biz_code"`
	Status    int    `yaml:"status"`
	Retryable bool   `yaml:"retryable"`
	I18n      string `yaml:"i18n"`
	Message   string `yaml:"message"`
}

type errorFile struct {
	ID           string       `yaml:"id"`
	Summary      string       `yaml:"summary"`
	Errors       []errorEntry `yaml:"errors"`
	CommonErrors []string     `yaml:"common_errors"`
	Order        []string     `yaml:"order"`
}

func main() {
	root := flag.String("root", "../..", "repo root")
	check := flag.Bool("check", false, "only verify errors.md is up to date")
	flag.Parse()

	abs, err := filepath.Abs(*root)
	if err != nil {
		fail(err)
	}
	dir := filepath.Join(abs, "contracts/platform/errors")
	files, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if err != nil {
		fail(err)
	}
	if len(files) == 0 {
		fail(fmt.Errorf("%s: no error files", dir))
	}
	sort.Strings(files)
	docs := map[string]errorFile{}
	for _, file := range files {
		b, err := os.ReadFile(file)
		if err != nil {
			fail(err)
		}
		var doc errorFile
		if err := yaml.Unmarshal(b, &doc); err != nil {
			fail(fmt.Errorf("%s: %w", file, err))
		}
		stem := strings.TrimSuffix(filepath.Base(file), filepath.Ext(file))
		docs[stem] = doc
	}
	base, ok := docs["_base"]
	if !ok {
		fail(fmt.Errorf("%s/_base.yaml is missing", dir))
	}
	var entries []errorEntry
	used := map[string]bool{}
	for _, stem := range base.Order {
		doc, ok := docs[stem]
		if !ok || len(doc.Errors) == 0 {
			fail(fmt.Errorf("_base.yaml order references missing/empty error file %s", stem))
		}
		entries = append(entries, doc.Errors...)
		used[stem] = true
	}
	for stem, doc := range docs {
		if len(doc.Errors) > 0 && !used[stem] {
			fail(fmt.Errorf("%s.yaml is not listed in _base.yaml order", stem))
		}
	}
	dataAccess := docs["data_access"].CommonErrors
	mdOut := render(entries, dataAccess)
	goRaw := renderGo(entries)
	goBytes, err := format.Source([]byte(goRaw))
	if err != nil {
		fail(fmt.Errorf("format errors_gen.go: %w", err))
	}
	goOut := string(goBytes)
	mdDst := filepath.Join(abs, "docs/contracts/generated/errors.md")
	goDst := filepath.Join(abs, "apps/api/internal/generated/errors_gen.go")
	if *check {
		for _, item := range []struct {
			path string
			want string
		}{{mdDst, mdOut}, {goDst, goOut}} {
			old, err := os.ReadFile(item.path)
			if err != nil {
				fail(err)
			}
			if string(old) != item.want {
				fail(fmt.Errorf("%s is stale; run make gen-errors", item.path))
			}
		}
		fmt.Println("errors.md: OK")
		fmt.Println("errors_gen.go: OK")
		return
	}
	for _, item := range []struct {
		path string
		data string
	}{{mdDst, mdOut}, {goDst, goOut}} {
		if err := os.MkdirAll(filepath.Dir(item.path), 0o755); err != nil {
			fail(err)
		}
		if err := os.WriteFile(item.path, []byte(item.data), 0o644); err != nil {
			fail(err)
		}
		fmt.Println("generated", item.path)
	}
}

func render(entries []errorEntry, dataAccess []string) string {
	var b strings.Builder
	b.WriteString("# 错误码\n\n")
	b.WriteString("> 本文件由 `contracts/platform/errors/*.yaml` 生成，禁止手改。生成命令：`make gen-errors`。\n\n")
	b.WriteString("**ID**: `platform.errors`\n\n")
	b.WriteString("| code | biz_code | status | retryable | i18n | message |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "| `%s` | %d | %d | %t | `%s` | %s |\n", e.Code, e.BizCode, e.Status, e.Retryable, e.I18n, escape(e.Message))
	}
	if len(dataAccess) > 0 {
		b.WriteString("\n## 数据访问基线\n\n")
		b.WriteString("以下错误由 repository / transaction 层统一映射，不写入每个 query 的 errors：\n\n")
		for _, code := range dataAccess {
			fmt.Fprintf(&b, "- `%s`\n", code)
		}
	}
	return b.String()
}

// renderGo 生成 Go 错误码常量与目录，供 HTTP 层等直接引用，避免手写 biz_code。
func renderGo(entries []errorEntry) string {
	var b strings.Builder
	b.WriteString("// Code generated by gen-errors from contracts/platform/errors/*.yaml; DO NOT EDIT.\n")
	b.WriteString("package generated\n\n")
	b.WriteString("// ErrorCode 是错误目录项。\n")
	b.WriteString("type ErrorCode struct {\n\tBizCode int\n\tStatus int\n\tRetryable bool\n}\n\n")
	b.WriteString("const (\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%s = %d\n", goName(e.Code), e.BizCode)
	}
	b.WriteString(")\n\n")
	b.WriteString("// ErrorCatalog 以 platform.errors.<CODE> 为键索引错误目录。\n")
	b.WriteString("var ErrorCatalog = map[string]ErrorCode{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t\"platform.errors.%s\": {BizCode: %s, Status: %d, Retryable: %t},\n", e.Code, goName(e.Code), e.Status, e.Retryable)
	}
	b.WriteString("}\n")
	return b.String()
}

// goName 把 COMMON_BAD_REQUEST 转成 CommonBadRequest；错误码全局唯一，失败时由 contract-check 拦截。
func goName(code string) string {
	parts := strings.Split(strings.ToLower(code), "_")
	var b strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

func escape(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen-errors:", err)
	os.Exit(1)
}
