// Command gen_model 从 data.entities / data.enums / data.tables 生成 Go 与 TS 模型。
//
// 输出：
//   - apps/api/internal/generated/model/model_gen.go（全部实体 + 枚举）
//   - apps/web/packages/api-client/src/generated/model.ts（public 实体 + 枚举）
//
// 只生成标量投影：关系字段（source.join）不进入模型，和 OpenAPI entitySchema 一致；
// secret 字段只进入 Go 模型，不进入 TS。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"gopkg.in/yaml.v3"

	"github.com/yourorg/web-seed/scripts/cmd/internal/contractspec"
)

const (
	goModelPath = "apps/api/internal/generated/model/model_gen.go"
	tsModelPath = "apps/web/packages/api-client/src/generated/model.ts"
	header      = "// Code generated by make gen-model; DO NOT EDIT.\n"
)

func main() {
	root := flag.String("root", "../..", "repository root")
	check := flag.Bool("check", false, "verify generated files are up to date")
	flag.Parse()

	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, "gen-model:", err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	abs, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	tableSchema, _, err := contractspec.LoadSchemaByType(abs, "data.tables")
	if err != nil {
		return err
	}
	enumSchema, _, err := contractspec.LoadSchemaByType(abs, "data.enums")
	if err != nil {
		return err
	}
	entitySchema, _, err := contractspec.LoadSchemaByType(abs, "data.entities")
	if err != nil {
		return err
	}

	tables, err := loadTableColumns(abs, tableSchema)
	if err != nil {
		return err
	}
	enums, err := loadEnums(abs, enumSchema)
	if err != nil {
		return err
	}
	entities, err := loadEntities(abs, entitySchema, tables, enums, tableSchema.ValueTypes.CustomTypes)
	if err != nil {
		return err
	}

	goSrc, err := renderGo(enums, entities)
	if err != nil {
		return err
	}
	tsSrc := renderTS(enums, entities)

	if check {
		for _, f := range []struct {
			path string
			want []byte
		}{
			{filepath.Join(abs, goModelPath), goSrc},
			{filepath.Join(abs, tsModelPath), tsSrc},
		} {
			got, err := os.ReadFile(f.path)
			if err != nil {
				return err
			}
			if !bytes.Equal(got, f.want) {
				return fmt.Errorf("%s is stale; run make gen-model", f.path)
			}
		}
		return nil
	}
	if err := writeFile(filepath.Join(abs, goModelPath), goSrc); err != nil {
		return err
	}
	if err := writeFile(filepath.Join(abs, tsModelPath), tsSrc); err != nil {
		return err
	}
	fmt.Printf("generated %s\n", goModelPath)
	fmt.Printf("generated %s\n", tsModelPath)
	return nil
}

type columnSpec struct {
	Family      string
	Custom      string
	Bits        int
	Precision   int
	Scale       int
	Nullable    bool
	PrimaryKey  bool
	Sensitivity string
}

type enumValue struct {
	Name string
	Code int
	Desc string
}

type enumSpec struct {
	ID     string
	GoType string
	TSType string
	Desc   string
	Values []enumValue
}

type fieldSpec struct {
	GoName      string
	JSONName    string
	GoType      string
	TSType      string
	Nullable    bool
	Sensitivity string
	Secret      bool
}

type entitySpec struct {
	ID     string
	GoName string
	Public bool
	Fields []fieldSpec
}

func loadTableColumns(root string, schema *contractspec.Schema) (map[string]map[string]columnSpec, error) {
	dir := filepath.Join(root, schema.Targets.Dir)
	basePath := filepath.Join(dir, "_base.yaml")
	baseDoc, err := loadYAML(basePath)
	if err != nil {
		return nil, err
	}
	baseCols := map[string]columnSpec{}
	parseColumnsInto(baseCols, baseDoc["columns"], schema.ValueTypes.CustomTypes)

	docs := map[string]map[string]any{}
	files, err := filepath.Glob(filepath.Join(dir, schema.Targets.Glob))
	if err != nil {
		return nil, err
	}
	for _, file := range files {
		if filepath.Base(file) == "_base.yaml" {
			continue
		}
		doc, err := loadYAML(file)
		if err != nil {
			return nil, err
		}
		id, _ := doc["id"].(string)
		if id == "" {
			id = schema.Targets.FileID(filepath.Base(file))
		}
		docs[id] = doc
	}
	out := map[string]map[string]columnSpec{}
	var resolve func(id string, seen map[string]bool) (map[string]columnSpec, error)
	resolve = func(id string, seen map[string]bool) (map[string]columnSpec, error) {
		if seen[id] {
			return nil, fmt.Errorf("cyclic table extends at %s", id)
		}
		seen[id] = true
		defer delete(seen, id)
		cols := map[string]columnSpec{}
		for k, v := range baseCols {
			cols[k] = v
		}
		doc := docs[id]
		if doc == nil {
			return cols, nil
		}
		for _, parent := range extends(doc) {
			if parent == "data.tables.base" {
				continue
			}
			parentCols, err := resolve(parent, seen)
			if err != nil {
				return nil, err
			}
			for k, v := range parentCols {
				cols[k] = v
			}
		}
		parseColumnsInto(cols, doc["columns"], schema.ValueTypes.CustomTypes)
		return cols, nil
	}
	for id := range docs {
		cols, err := resolve(id, map[string]bool{})
		if err != nil {
			return nil, err
		}
		out[id] = cols
	}
	return out, nil
}

func extends(doc map[string]any) []string {
	table, _ := asMap(doc["table"])
	var out []string
	for _, raw := range asList(table["extends"]) {
		if s, ok := raw.(string); ok && s != "" {
			out = append(out, s)
		}
	}
	return out
}

func parseColumnsInto(out map[string]columnSpec, raw any, customs map[string]contractspec.CustomValueType) {
	for _, item := range asList(raw) {
		m, _ := asMap(item)
		name, _ := m["name"].(string)
		if name == "" {
			continue
		}
		typ, _ := m["type"].(string)
		typ = strings.TrimPrefix(typ, "_types.basics.")
		spec := columnSpec{}
		if custom, ok := customs[typ]; ok {
			spec.Custom = typ
			spec.Family = custom.Family
			applyParams(&spec, custom.Params)
		} else {
			spec.Family = typ
			applyParams(&spec, m)
		}
		spec.Nullable, _ = m["nullable"].(bool)
		spec.PrimaryKey, _ = m["primary_key"].(bool)
		spec.Sensitivity, _ = m["sensitivity"].(string)
		if spec.Family == "integer" && spec.Bits == 0 {
			spec.Bits = 32
		}
		out[name] = spec
	}
}

func applyParams(spec *columnSpec, params any) {
	m, _ := asMap(params)
	if v, ok := toInt(m["bits"]); ok {
		spec.Bits = v
	}
	if v, ok := toInt(m["precision"]); ok {
		spec.Precision = v
	}
	if v, ok := toInt(m["scale"]); ok {
		spec.Scale = v
	}
}

func loadEnums(root string, schema *contractspec.Schema) (map[string]enumSpec, error) {
	out := map[string]enumSpec{}
	files, err := filepath.Glob(filepath.Join(root, schema.Targets.Dir, schema.Targets.Glob))
	if err != nil {
		return nil, err
	}
	for _, file := range files {
		doc, err := loadYAML(file)
		if err != nil {
			return nil, err
		}
		for _, raw := range asList(doc["enums"]) {
			m, _ := asMap(raw)
			name, _ := m["name"].(string)
			if name == "" {
				continue
			}
			spec := enumSpec{
				ID:     "data.enums." + name,
				GoType: stringValue(m["go_type"]),
				TSType: stringValue(m["ts_type"]),
				Desc:   stringValue(m["description"]),
			}
			for _, rv := range asList(m["values"]) {
				vm, _ := asMap(rv)
				spec.Values = append(spec.Values, enumValue{
					Name: stringValue(vm["value"]),
					Code: intValue(vm["code"]),
					Desc: stringValue(vm["description"]),
				})
			}
			out[spec.ID] = spec
		}
	}
	return out, nil
}

func loadEntities(root string, schema *contractspec.Schema, tables map[string]map[string]columnSpec, enums map[string]enumSpec, customs map[string]contractspec.CustomValueType) ([]entitySpec, error) {
	files, err := filepath.Glob(filepath.Join(root, schema.Targets.Dir, schema.Targets.Glob))
	if err != nil {
		return nil, err
	}
	var out []entitySpec
	for _, file := range files {
		if filepath.Base(file) == "_base.yaml" {
			continue
		}
		doc, err := loadYAML(file)
		if err != nil {
			return nil, err
		}
		model, _ := asMap(doc["model"])
		goName := stringValue(model["name"])
		if goName == "" {
			continue
		}
		var primary string
		if list := asList(model["tables"]); len(list) > 0 {
			primary, _ = list[0].(string)
		}
		primCols := tables[primary]
		spec := entitySpec{ID: stringValue(doc["id"]), GoName: goName, Public: firstUpper(goName)}
		base := baseFields(primCols)
		baseNames := map[string]int{}
		for i := range base {
			baseNames[base[i].GoName] = i
		}
		for _, raw := range asList(doc["fields"]) {
			m, _ := asMap(raw)
			f, ok := entityField(m, tables, primary, enums, customs)
			if !ok {
				continue
			}
			if idx, isBase := baseNames[f.GoName]; isBase {
				base[idx] = f
				continue
			}
			spec.Fields = append(spec.Fields, f)
		}
		spec.Fields = append(base, spec.Fields...)
		out = append(out, spec)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out, nil
}

func baseFields(cols map[string]columnSpec) []fieldSpec {
	id := cols["id"]
	status := cols["status"]
	return []fieldSpec{
		{GoName: "ID", JSONName: "id", GoType: goScalar(id, false), TSType: tsScalar(id, false), Sensitivity: "public"},
		{GoName: "Status", JSONName: "status", GoType: goScalar(status, false), TSType: tsScalar(status, false), Sensitivity: "public"},
		{GoName: "CreatedAt", JSONName: "created_at", GoType: "time.Time", TSType: "string", Sensitivity: "public"},
		{GoName: "UpdatedAt", JSONName: "updated_at", GoType: "time.Time", TSType: "string", Sensitivity: "public"},
		{GoName: "DeletedAt", JSONName: "deleted_at", GoType: "*time.Time", TSType: "string", Nullable: true, Sensitivity: "public"},
	}
}

func entityField(m map[string]any, tables map[string]map[string]columnSpec, primary string, enums map[string]enumSpec, customs map[string]contractspec.CustomValueType) (fieldSpec, bool) {
	name := stringValue(m["name"])
	if name == "" {
		return fieldSpec{}, false
	}
	source, _ := asMap(m["source"])
	if _, ok := asMap(source["join"]); ok {
		return fieldSpec{}, false // 关系字段不进入标量模型
	}
	typ := strings.TrimPrefix(stringValue(m["type"]), "*")
	pointer := strings.HasPrefix(stringValue(m["type"]), "*")
	if strings.HasPrefix(typ, "data.entities.") || strings.HasPrefix(typ, "_types.structures.list<data.entities.") {
		return fieldSpec{}, false
	}
	nullable, hasNullable := m["nullable"].(bool)
	if pointer && !hasNullable {
		nullable, hasNullable = true, true
	}
	sensitivity := stringValue(m["sensitivity"])

	var spec columnSpec
	if typ == "" {
		if ref := stringValue(source["column"]); ref != "" {
			table, col, ok := splitColumnRef(ref)
			if ok {
				spec = tables[table][col]
				if !hasNullable {
					nullable = spec.Nullable
				}
				if sensitivity == "" {
					sensitivity = spec.Sensitivity
				}
			}
		}
	} else if strings.HasPrefix(typ, "data.enums.") {
		enum, ok := enums[typ]
		if !ok {
			return fieldSpec{}, false
		}
		if ref := stringValue(source["column"]); ref != "" {
			table, col, ok := splitColumnRef(ref)
			if ok {
				colSpec := tables[table][col]
				if !hasNullable {
					nullable = colSpec.Nullable
				}
				if sensitivity == "" {
					sensitivity = colSpec.Sensitivity
				}
			}
		}
		if sensitivity == "" {
			sensitivity = "public"
		}
		jsonName := stringValue(m["json_name"])
		if jsonName == "" {
			jsonName = contractspec.SnakeCase(name)
		}
		goType := enum.GoType
		if nullable {
			goType = "*" + goType
		}
		return fieldSpec{GoName: name, JSONName: jsonName, GoType: goType, TSType: enum.TSType, Nullable: nullable, Sensitivity: sensitivity, Secret: sensitivity == "secret"}, true
	} else {
		spec = typeSpec(typ, customs)
	}

	if spec.Family == "" {
		return fieldSpec{}, false
	}
	jsonName := stringValue(m["json_name"])
	if jsonName == "" {
		jsonName = contractspec.SnakeCase(name)
	}
	if sensitivity == "" {
		sensitivity = "public"
	}
	return fieldSpec{
		GoName:      name,
		JSONName:    jsonName,
		GoType:      goScalar(spec, nullable),
		TSType:      tsScalar(spec, nullable),
		Nullable:    nullable,
		Sensitivity: sensitivity,
		Secret:      sensitivity == "secret",
	}, true
}

func typeSpec(typ string, customs map[string]contractspec.CustomValueType) columnSpec {
	spec := columnSpec{Family: typ}
	if custom, ok := customs[typ]; ok {
		spec.Custom = typ
		spec.Family = custom.Family
		applyParams(&spec, custom.Params)
	}
	if spec.Family == "integer" && spec.Bits == 0 {
		spec.Bits = 32
	}
	return spec
}

func goScalar(spec columnSpec, nullable bool) string {
	var typ string
	switch spec.Family {
	case "string":
		typ = "string"
	case "boolean":
		typ = "bool"
	case "integer":
		switch spec.Bits {
		case 8:
			typ = "int8"
		case 16:
			typ = "int16"
		case 64:
			typ = "int64"
		default:
			typ = "int32"
		}
	case "float":
		if spec.Bits == 32 {
			typ = "float32"
		} else {
			typ = "float64"
		}
	case "decimal":
		typ = "string" // 精确小数用字符串，避免 float 精度丢失
	case "timestamp", "datetime":
		typ = "time.Time"
	case "json":
		typ = "json.RawMessage"
	case "bytes":
		typ = "[]byte"
	case "any":
		typ = "any"
	default:
		typ = "any"
	}
	if nullable && !isNilable(typ) {
		return "*" + typ
	}
	return typ
}

func tsScalar(spec columnSpec, nullable bool) string {
	var typ string
	switch spec.Family {
	case "string":
		typ = "string"
	case "boolean":
		typ = "boolean"
	case "integer", "float":
		typ = "number"
	case "decimal":
		typ = "string"
	case "timestamp", "datetime":
		typ = "string"
	case "json", "any":
		typ = "unknown"
	case "bytes":
		typ = "string"
	default:
		typ = "unknown"
	}
	if nullable && typ != "unknown" {
		return typ + " | null"
	}
	return typ
}

func isNilable(typ string) bool {
	return typ == "json.RawMessage" || typ == "[]byte" || typ == "any"
}

func renderGo(enums map[string]enumSpec, entities []entitySpec) ([]byte, error) {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\npackage model\n\n")
	hasEnums := len(enums) > 0
	hasJSON, hasTime := false, false
	for _, e := range entities {
		for _, f := range e.Fields {
			if f.GoType == "json.RawMessage" {
				hasJSON = true
			}
			if strings.Contains(f.GoType, "time.Time") {
				hasTime = true
			}
		}
	}
	var imports []string
	if hasEnums || hasJSON {
		imports = append(imports, "\"encoding/json\"")
	}
	if hasEnums {
		imports = append(imports, "\"fmt\"")
	}
	if hasTime {
		imports = append(imports, "\"time\"")
	}
	if len(imports) > 0 {
		b.WriteString("import (\n")
		for _, imp := range imports {
			fmt.Fprintf(&b, "\t%s\n", imp)
		}
		b.WriteString(")\n\n")
	}

	enumIDs := make([]string, 0, len(enums))
	for id := range enums {
		enumIDs = append(enumIDs, id)
	}
	sort.Strings(enumIDs)
	for _, id := range enumIDs {
		e := enums[id]
		fmt.Fprintf(&b, "// %s %s\n", e.GoType, e.Desc)
		fmt.Fprintf(&b, "type %s int32\n\nconst (\n", e.GoType)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "\t%s%s %s = %d // %s\n", e.GoType, pascal(v.Name), e.GoType, v.Code, v.Desc)
		}
		b.WriteString(")\n\n")
		fmt.Fprintf(&b, "func (s %s) String() string {\n\tswitch s {\n", e.GoType)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "\tcase %s%s:\n\t\treturn %q\n", e.GoType, pascal(v.Name), v.Name)
		}
		b.WriteString("\tdefault:\n\t\treturn \"\"\n\t}\n}\n\n")
		fmt.Fprintf(&b, "func Parse%s(v string) (%s, error) {\n\tswitch v {\n", e.GoType, e.GoType)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "\tcase %q:\n\t\treturn %s%s, nil\n", v.Name, e.GoType, pascal(v.Name))
		}
		fmt.Fprintf(&b, "\tdefault:\n\t\treturn 0, fmt.Errorf(\"unknown %s %%q\", v)\n\t}\n}\n\n", e.GoType)
		fmt.Fprintf(&b, "func (s %s) MarshalJSON() ([]byte, error) {\n\tname := s.String()\n\tif name == \"\" {\n\t\treturn nil, fmt.Errorf(\"unknown %s %%d\", int32(s))\n\t}\n\treturn json.Marshal(name)\n}\n\n", e.GoType, e.GoType)
		fmt.Fprintf(&b, "func (s *%s) UnmarshalJSON(data []byte) error {\n\tvar v string\n\tif err := json.Unmarshal(data, &v); err != nil {\n\t\treturn err\n\t}\n\tparsed, err := Parse%s(v)\n\tif err != nil {\n\t\treturn err\n\t}\n\t*s = parsed\n\treturn nil\n}\n\n", e.GoType, e.GoType)
	}

	for _, e := range entities {
		comment := "标量投影；关系字段按需加载"
		if !e.Public {
			comment = "内部标量投影；关系字段按需加载"
		}
		fmt.Fprintf(&b, "// %s 是 %s 的%s。\n", e.GoName, e.ID, comment)
		fmt.Fprintf(&b, "type %s struct {\n", e.GoName)
		for _, f := range e.Fields {
			tag := ""
			if isExportedGo(f.GoName) {
				tag = fmt.Sprintf(" `json:%q`", f.JSONName)
			}
			fmt.Fprintf(&b, "\t%s %s%s\n", f.GoName, f.GoType, tag)
		}
		b.WriteString("}\n\n")
	}
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return out, nil
}

func renderTS(enums map[string]enumSpec, entities []entitySpec) []byte {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n")
	enumIDs := make([]string, 0, len(enums))
	for id := range enums {
		enumIDs = append(enumIDs, id)
	}
	sort.Strings(enumIDs)
	for _, id := range enumIDs {
		e := enums[id]
		fmt.Fprintf(&b, "export const %s = {\n", e.TSType)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "  %s: %q,\n", pascal(v.Name), v.Name)
		}
		fmt.Fprintf(&b, "} as const\n\n")
		fmt.Fprintf(&b, "export type %s = (typeof %s)[keyof typeof %s]\n\n", e.TSType, e.TSType, e.TSType)
	}
	for _, e := range entities {
		if !e.Public {
			continue
		}
		fmt.Fprintf(&b, "export interface %s {\n", e.GoName)
		for _, f := range e.Fields {
			if f.Secret {
				continue
			}
			optional := ""
			if f.Nullable {
				optional = "?"
			}
			tsType := f.TSType
			if f.Nullable && tsType != "unknown" && !strings.Contains(tsType, "| null") {
				tsType += " | null"
			}
			fmt.Fprintf(&b, "  %s%s: %s\n", f.JSONName, optional, tsType)
		}
		b.WriteString("}\n\n")
	}
	return []byte(b.String())
}

func firstUpper(s string) bool {
	for _, r := range s {
		return unicode.IsUpper(r)
	}
	return false
}

// isExportedGo 判断字段名是否导出；未导出字段不写 json tag（go vet 也要求如此）。
func isExportedGo(s string) bool {
	return firstUpper(s)
}

func pascal(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		r := []rune(p)
		b.WriteString(strings.ToUpper(string(r[0])))
		b.WriteString(string(r[1:]))
	}
	return b.String()
}

func loadYAML(path string) (map[string]any, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc map[string]any
	if err := yaml.Unmarshal(b, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return doc, nil
}

func splitColumnRef(ref string) (table, col string, ok bool) {
	parts := strings.Split(ref, ".col.")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return "", "", false
	}
	return parts[0], parts[1], true
}

func asMap(v any) (map[string]any, bool) {
	m, ok := v.(map[string]any)
	return m, ok
}

func asList(v any) []any {
	l, _ := v.([]any)
	return l
}

func stringValue(v any) string {
	s, _ := v.(string)
	return s
}

func intValue(v any) int {
	n, _ := toInt(v)
	return n
}

func toInt(v any) (int, bool) {
	switch x := v.(type) {
	case int:
		return x, true
	case int64:
		return int(x), true
	case float64:
		return int(x), true
	}
	return 0, false
}

func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}
